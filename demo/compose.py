"""Compose the narrated 30-second demo: site recording + ElevenLabs voice + rain ambience + captions + SI watermark.

Written and run by Claude Code (Claude Opus 5.5), an SI tool. The voice (eleven_v4) and the rain
ambience (sound-generation) are SI-generated by ElevenLabs; demo/narration.json records the text,
models and timing, and the output file's metadata says so too.
Usage: node demo/record-site.cjs first, then  python3 demo/compose.py
"""
import json
import subprocess
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
LENGTH = 30.0
OUT = HERE / "ulan-demo.mp4"


def caption_png(text, path):
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--default-background-color=00000000",
                    "--window-size=1280,110", f"--screenshot={path}", f"file://{HERE / 'caption.html'}#{quote(text)}"],
                   check=True, capture_output=True)


def main():
    narration = json.loads((HERE / "narration.json").read_text())
    marks = json.loads((HERE / "site-raw" / "marks.json").read_text())
    raw = HERE / "site-raw" / marks["video"]
    duration = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(raw)],
                                    check=True, capture_output=True, text=True).stdout)
    start = round(max(0.0, marks["ready"] - (marks["end"] - duration)), 3)  # the recording starts a little after the script's clock

    lines = narration["lines"]
    captions = []
    for i, line in enumerate(lines):
        png = HERE / "site-raw" / f"caption{i + 1}.png"
        caption_png(line["text"], png)
        end = lines[i + 1]["start"] if i + 1 < len(lines) else LENGTH
        captions.append((png, line["start"], end))

    inputs = ["-ss", str(start), "-t", str(LENGTH), "-i", str(raw), "-i", str(HERE / "watermark.png")]
    for png, _, _ in captions:
        inputs += ["-i", str(png)]
    for line in lines:
        inputs += ["-i", str(HERE / line["file"])]
    inputs += ["-stream_loop", "-1", "-i", str(HERE / "audio" / "rain.mp3")]

    n_cap, n_voice = len(captions), len(lines)
    video = "[0:v][1:v]overlay=W-w-70:58[v0]"
    for i, (_, a, b) in enumerate(captions):
        video += f";[v{i}][{2 + i}:v]overlay=0:H-h-14:enable='between(t,{a},{b - 0.05})'[v{i + 1}]"
    voice_inputs = range(2 + n_cap, 2 + n_cap + n_voice)
    audio = "".join(f"[{k}:a]adelay={int(lines[j]['start'] * 1000)}:all=1[a{j}];" for j, k in enumerate(voice_inputs))
    audio += "".join(f"[a{j}]" for j in range(n_voice)) + f"amix=inputs={n_voice}:normalize=0,loudnorm=I=-16:TP=-1.5[voice];"
    rain = 2 + n_cap + n_voice
    audio += (f"[{rain}:a]atrim=0:{LENGTH},volume=0.16,afade=t=in:d=1.2,afade=t=out:st={LENGTH - 1.5}:d=1.5[rain];"
              f"[voice][rain]amix=inputs=2:normalize=0,atrim=0:{LENGTH}[aout]")
    meta = ("SI-generated content. Narration: ElevenLabs eleven_v4 text-to-speech. Rain ambience: ElevenLabs sound generation. "
            "Website tour scripted, recorded and edited by Claude Code (Claude Opus 5.5).")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *inputs,
                    "-filter_complex", f"{video};{audio}", "-map", f"[v{n_cap}]", "-map", "[aout]",
                    "-c:v", "libx264", "-pix_fmt", "yuv420p", "-r", "30", "-c:a", "aac", "-b:a", "160k", "-t", str(LENGTH),
                    "-metadata", "title=Ulan, measured: NASA Space Apps 2026 demo",
                    "-metadata", f"comment={meta}", "-metadata", f"description={meta}",
                    "-movflags", "+faststart", str(OUT)], check=True)
    print(OUT)


if __name__ == "__main__":
    main()
